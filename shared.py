# Monotonic revision bumped on every user/inbound change so edges can cheaply
# detect drift with a conditional pull (If-None-Match style).
EDGE_REVISION: int = 1

# Traffic deltas reported by edges, buffered here before being flushed into the
# user records by the master (batched under USERS_LOCK to stay thread-safe).
