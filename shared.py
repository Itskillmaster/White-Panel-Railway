def derive_proto_password(config_uuid: str, secret: str, salt: str) -> str:
    """Deterministic per-protocol password (Hysteria2 auth / TUIC v5 password).

    Derived from the user's config UUID + panel secret so it never needs to be
    stored or migrated; both master and edge nodes compute identical values.
    """
    return hmac.new(
        f"{salt}".encode(), f"{config_uuid}:{secret}".encode(), hashlib.sha256
    ).hexdigest()[:22]


