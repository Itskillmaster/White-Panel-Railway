# POST-SQLITE MIGRATION NOTES
# ───────────────────────────
# SQLite (database.py, WAL mode) is now the SYSTEM OF RECORD. The dicts below
# are a hot read cache for per-connection work (relay lookups, subscription
# rendering) where a disk round-trip would be unacceptable.
#
# The asyncio.Lock objects here no longer coordinate PERSISTENCE (that moved to
# SQLite's single-writer discipline inside database.write_txn); they now guard
# only microsecond-scale read-modify-write cycles on the cache itself. They are
# uncontended in practice and cheaper than any cross-process alternative.
